"""ACEkor Grading Sheet brand assets from one drawing (logo C: clipboard class record).

Usage (from the repository root):  python3 -I acekor/tools/brand.py
Needs Node with Playwright/Chromium (renders the SVG/HTML) and Pillow (resizes).

Writes:
  app/android/app/src/main/res/drawable/ic_launcher_foreground.xml   adaptive icon (vector)
  app/android/app/src/main/res/drawable/ic_launcher_monochrome.xml   themed icon (vector)
  app/android/app/src/main/res/drawable/ic_notification.xml          status-bar icon (vector)
  app/android/app/src/main/res/mipmap-*/ic_launcher.png              Android 7.x fallback
  store/play_icon_512.png, store/feature_graphic_1024x500.png
  store/logo_1024.png (transparent), store/logo_wordmark.png
"""
import os
import subprocess
import tempfile

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "app/android/app/src/main/res")
STORE = os.path.join(ROOT, "store")
FONTS = os.path.join(ROOT, "app/assets/fonts")

BG = "#0B0B0C"
PAPER = "#F5F8F7"
LINE = "#AEBDB8"
GREEN = "#13A57C"
TEAL = "#2CC5A0"
DEEP = "#0A6B54"
CLIP = "#9FB1AB"
TRACK = "#DDE6E3"


def rrect(x, y, w, h, r):
    return (f"M{x+r},{y} H{x+w-r} A{r},{r} 0 0 1 {x+w},{y+r} V{y+h-r} A{r},{r} 0 0 1 {x+w-r},{y+h} "
            f"H{x+r} A{r},{r} 0 0 1 {x},{y+h-r} V{y+r} A{r},{r} 0 0 1 {x+r},{y} Z")


def circle(cx, cy, r):
    return f"M{cx-r},{cy} A{r},{r} 0 1 0 {cx+r},{cy} A{r},{r} 0 1 0 {cx-r},{cy} Z"


def polyline(points):
    return "M" + " L".join(f"{x},{y}" for x, y in points)


ROWS = [42, 52, 62]

# The logo, in a 108 x 108 box (centre 54, 54). Content spans x 29-79, y 20-87.
LOGO = [
    ("fill", rrect(29, 25, 50, 62, 7), DEEP),                  # clipboard
    ("fill", rrect(34, 32, 40, 50, 3.5), PAPER),               # grading sheet
    ("fill", rrect(43, 20, 22, 11, 4), CLIP),                  # clip
    ("fill", circle(54, 24.5, 2.4), DEEP),                     # clip hole
]
for ry in ROWS:
    LOGO.append(("stroke", polyline([(39.5, ry), (42, ry + 2.5), (46.5, ry - 2.5)]), GREEN, 2.3))
    LOGO.append(("fill", rrect(50, ry - 2, 19, 4, 2), LINE))
LOGO += [("fill", rrect(39, 71, 30, 5, 2.5), TRACK), ("fill", rrect(39, 71, 25, 5, 2.5), TEAL)]

# One-colour version: the sheet is a hole in the clipboard (even-odd), marks drawn on top.
MONO = [
    ("fill-evenodd", rrect(29, 25, 50, 62, 7) + " " + rrect(34, 32, 40, 50, 3.5)),
    ("fill-evenodd", rrect(43, 20, 22, 11, 4) + " " + circle(54, 24.5, 2.4)),
]
for ry in ROWS:
    MONO.append(("stroke", polyline([(39.5, ry), (42, ry + 2.5), (46.5, ry - 2.5)]), 2.6))
    MONO.append(("fill", rrect(50, ry - 2, 19, 4, 2)))
MONO.append(("fill", rrect(39, 71, 25, 5, 2.5)))


def vector(items, scale, mono=False, size="108dp"):
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by acekor/tools/brand.py — ACEkor logo: clipboard class record. -->",
        f'<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="{size}" '
        f'android:height="{size}" android:viewportWidth="108" android:viewportHeight="108">',
        f'    <group android:pivotX="54" android:pivotY="54" android:scaleX="{scale}" android:scaleY="{scale}">',
    ]
    for it in items:
        if it[0] == "stroke":
            color = "#FFFFFF" if mono else it[2]
            width = it[2] if mono else it[3]
            out.append(f'        <path android:pathData="{it[1]}" android:fillColor="#00000000" android:strokeColor="{color}" '
                       f'android:strokeWidth="{width}" android:strokeLineCap="round" android:strokeLineJoin="round" />')
        else:
            color = "#FFFFFF" if mono else it[2]
            ft = ' android:fillType="evenOdd"' if it[0] == "fill-evenodd" else ""
            out.append(f'        <path android:pathData="{it[1]}" android:fillColor="{color}"{ft} />')
    out += ["    </group>", "</vector>", ""]
    return "\n".join(out)


def svg(scale=1.0, background=None, radius=0, size=1024):
    parts = []
    if background:
        parts.append(f'<rect width="108" height="108" rx="{radius}" fill="{background}"/>')
    t = f"translate({54*(1-scale)},{54*(1-scale)}) scale({scale})"
    body = []
    for it in LOGO:
        if it[0] == "stroke":
            body.append(f'<path d="{it[1]}" fill="none" stroke="{it[2]}" stroke-width="{it[3]}" '
                        'stroke-linecap="round" stroke-linejoin="round"/>')
        else:
            body.append(f'<path d="{it[1]}" fill="{it[2]}"/>')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="{size}" height="{size}">'
            + "".join(parts) + f'<g transform="{t}">' + "".join(body) + "</g></svg>")


def font_face():
    return (f"@font-face{{font-family:R;src:url(file://{FONTS}/Roboto-Regular.ttf)}}"
            f"@font-face{{font-family:R;font-weight:700;src:url(file://{FONTS}/Roboto-Bold.ttf)}}")


def render(html, out, width, height, transparent=False):
    js = os.path.join(os.path.dirname(os.path.abspath(__file__)), "render_page.js")
    with tempfile.TemporaryDirectory() as d:
        page = os.path.join(d, "page.html")
        with open(page, "w") as f:
            f.write(html)
        subprocess.run(["node", js, page, out, str(width), str(height), "1" if transparent else "0"], check=True)


def page(body, w, h, bg="transparent"):
    return (f"<!doctype html><html><head><meta charset='utf-8'><style>{font_face()}"
            f"html,body{{margin:0;width:{w}px;height:{h}px;background:{bg};overflow:hidden;font-family:R}}</style>"
            f"</head><body>{body}</body></html>")


def feature_graphic():
    keys = [["7", "8", "9"], ["4", "5", "6"], ["1", "2", "3"], ["⌫", "0", "✓"]]
    pad = "".join(
        f"<div style='display:flex;gap:46px;margin-top:10px'>" + "".join(
            f"<div style='width:52px;height:52px;border-radius:50%;display:flex;align-items:center;justify-content:center;"
            f"font-size:{24 if k not in '⌫✓' else 26}px;background:{GREEN if k == '✓' else '#2A2A2C'};"
            f"color:{'#FF5A52' if k == '⌫' else '#fff'};font-weight:{700 if k == '✓' else 400}'>{k}</div>" for k in row)
        + "</div>" for row in keys)
    body = f"""
    <div style="position:absolute;left:64px;top:70px;width:520px">
      <div style="display:flex;align-items:center;gap:24px">{svg(1.3, None, 0, 150)}
        <div><div style="font-size:84px;font-weight:700;color:#fff;letter-spacing:1px;line-height:1">ACEkor</div>
        <div style="font-size:26px;font-weight:700;color:{TEAL};letter-spacing:7px;margin-top:12px">GRADING SHEET</div></div></div>
      <div style="font-size:31px;color:#B9C4C0;margin-top:56px">Search. Score. Save.</div>
      <div style="font-size:31px;color:#B9C4C0;margin-top:8px">Works offline.</div>
    </div>
    <div style="position:absolute;right:58px;top:28px;width:330px;color:#fff">
      <div style="font-size:17px;font-weight:700;letter-spacing:.5px"><span style="color:#A1A1A6">STUDENT:</span> JUAN DELA CRUZ</div>
      <div style="font-size:22px;font-weight:700;margin-top:8px">QUIZ 1</div>
      <div style="font-size:66px;text-align:center;margin-top:4px;line-height:1.1">42/50</div>
      <div style="font-size:36px;text-align:center;color:{TEAL};margin-bottom:6px">84%</div>
      <div style="display:flex;flex-direction:column;align-items:center">{pad}</div>
    </div>"""
    return page(body, 1024, 500, BG)


def main():
    os.makedirs(STORE, exist_ok=True)
    draw = os.path.join(RES, "drawable")
    with open(os.path.join(draw, "ic_launcher_foreground.xml"), "w") as f:
        f.write(vector(LOGO, 0.8))                   # inside the 66 dp safe zone
    with open(os.path.join(draw, "ic_launcher_monochrome.xml"), "w") as f:
        f.write(vector(MONO, 0.8, mono=True))
    with open(os.path.join(draw, "ic_notification.xml"), "w") as f:
        f.write(vector(MONO, 1.45, mono=True, size="24dp"))

    with tempfile.TemporaryDirectory() as d:
        legacy = os.path.join(d, "legacy.png")
        render(page(svg(1.05, BG, 24), 1024, 1024), legacy, 1024, 1024, transparent=True)
        img = Image.open(legacy).convert("RGBA")
        for density, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
            img.resize((px, px), Image.LANCZOS).save(os.path.join(RES, f"mipmap-{density}", "ic_launcher.png"))
        play = os.path.join(d, "play.png")
        render(page(svg(1.1, BG, 0), 1024, 1024), play, 1024, 1024)
        Image.open(play).convert("RGB").resize((512, 512), Image.LANCZOS).save(os.path.join(STORE, "play_icon_512.png"))
    render(page(svg(1.25), 1024, 1024), os.path.join(STORE, "logo_1024.png"), 1024, 1024, transparent=True)
    lockup = (f"<div style='display:flex;align-items:center;gap:28px;padding:40px 56px'>{svg(1.3, None, 0, 220)}"
              f"<div><div style='font-size:120px;font-weight:700;color:#fff;line-height:1'>ACEkor</div>"
              f"<div style='font-size:38px;font-weight:700;color:{TEAL};letter-spacing:10px;margin-top:16px'>GRADING SHEET</div>"
              f"</div></div>")
    render(page(lockup, 1200, 300, BG), os.path.join(STORE, "logo_wordmark.png"), 1200, 300)
    render(feature_graphic(), os.path.join(STORE, "feature_graphic_1024x500.png"), 1024, 500)
    print("brand assets written")


if __name__ == "__main__":
    main()
