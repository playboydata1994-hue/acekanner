import kotlin.test.assertIs
import org.opencv.core.Core
import org.opencv.core.CvType
import org.opencv.core.Mat
import org.opencv.core.Point
import org.opencv.core.Scalar
import org.opencv.core.Size
import org.opencv.imgcodecs.Imgcodecs
import org.opencv.imgproc.Imgproc

/**
 * End-to-end on the real artefact: PDFs generated by the app
 * (test/services/answer_sheet_pdf_test.dart), rasterized with pdftoppm at
 * 12 px/mm, marked like a student would, photographed, and read.
 */
class PrintedSheetTest {
    private val pxPerMm = 12.0

    @BeforeTest
    fun setUp() = loadOpenCv()

    private class Fixture(val png: String, val layout: String, val pageW: Double, val pageH: Double)

    private val fixtures = listOf(
        Fixture("a4-ack3-50-d10-s1", "ack3-50-d10-s1", 210.0, 297.0),
        // These two carry the sample school logo beside the top-left marker.
        Fixture("letter-ack3-75-d9-s2", "ack3-75-d9-s2", 215.9, 279.4),
        Fixture("long-ack3-100-d12-s4", "ack3-100-d12-s4", 215.9, 330.2),
    )

    @Test
    fun `printed sheets on A4, Letter and 8x13 are read end to end`() {
        val engine = OmrEngine()
        for ((i, f) in fixtures.withIndex()) {
            val layout = loadLayout(f.layout)
            val page = Imgcodecs.imread("src/test/resources/sheets/${f.png}.png", Imgcodecs.IMREAD_GRAYSCALE)
            check(!page.empty()) { "Missing ${f.png}.png: run omr_engine/tool/render_fixtures.sh" }
            val offset = PointMm((f.pageW - layout.frameWidthMm) / 2, (f.pageH - layout.frameHeightMm) / 2)
            val rnd = Random(100 + i)
            val answers = IntArray(layout.itemCount) { rnd.nextInt(5) }
            val digits = (1..layout.idDigits).map { rnd.nextInt(10) }.joinToString("")
            val set = if (layout.setCount > 1) rnd.nextInt(layout.setCount) else null

            fun shade(c: PointMm, rxMm: Double, ryMm: Double) {
                val center = Point((c.x + offset.x) * pxPerMm, (c.y + offset.y) * pxPerMm)
                val mask = Mat(page.size(), CvType.CV_8UC1, Scalar(0.0))
                val axes = Size(rxMm * 0.95 * pxPerMm, ryMm * 0.95 * pxPerMm)
                Imgproc.ellipse(mask, center, axes, 0.0, 0.0, 360.0, Scalar(255.0), -1, Imgproc.LINE_AA)
                val ink = Mat(page.size(), CvType.CV_8UC1)
                Core.randn(ink, 70.0, 20.0)
                val darker = Mat()
                Core.min(page, ink, darker)
                darker.copyTo(page, mask)
                mask.release(); ink.release(); darker.release()
            }
            answers.forEachIndexed { q, c -> shade(layout.questions[q][c], layout.bubbleRxMm, layout.bubbleRyMm) }
            digits.forEachIndexed { col, ch -> shade(layout.idColumns[col][ch - '0'], layout.idBubbleRxMm, layout.idBubbleRyMm) }
            set?.let { shade(layout.setBubbles[it], layout.bubbleRxMm, layout.bubbleRyMm) }

            val photo = PhotoSimulator.photograph(
                page,
                PhotoParams(rotationDeg = rnd.nextDouble(-10.0, 10.0), tilt = 0.03, blurSigma = 1.0, noiseSigma = 3.0, lightLow = 0.7, jpegQuality = 85),
                rnd,
            )
            val out = File("build/printed-${f.png}-rectified.jpg").absolutePath
            val result = assertIs<OmrOutcome.Success>(engine.analyze(photo, layout, rectifiedPath = out))
            println("PRINTED ${f.png}: quality=${result.quality.toJson()} qr=${result.qrText} ms=${result.elapsedMs}")

            answers.forEachIndexed { q, c ->
                val r = result.questions[q]
                assertEquals(MarkState.ANSWERED, r.state, "${f.png} q${q + 1}")
                assertEquals(1 shl c, r.mask, "${f.png} q${q + 1}")
            }
            assertEquals(digits, result.studentNumber, "${f.png} student number")
            if (set != null) assertEquals(1 shl set, result.set!!.mask)
            assertEquals("ACK3|K7M2Q9XA|${layout.itemCount}|${layout.idDigits}|${layout.setCount}|G", result.qrText)
            check(File(out).length() > 10_000) { "rectified image not written" }
            page.release(); photo.release()
        }
    }
}
