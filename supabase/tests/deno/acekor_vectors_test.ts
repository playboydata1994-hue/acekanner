// Test vectors shared with ACEKOR Calculator
// (acekor/app/test/fixtures/acekor_entitlement_vectors.json): the Dart
// verifier must accept exactly what this server signs.
import { assertEquals } from "jsr:@std/assert@1.0.13";
import { ACEKOR_TOKEN_TYPE, buildAcekorClaims } from "../../functions/_shared/acekor.ts";
import { signerFromSeed, TOKEN_TYPE } from "../../functions/_shared/jws.ts";
import { TEST_SEED } from "./helpers.ts";

const path = new URL("../../../acekor/app/test/fixtures/acekor_entitlement_vectors.json", import.meta.url);

async function vectors() {
  const s = await signerFromSeed(TEST_SEED, "test", ACEKOR_TOKEN_TYPE);
  const now = new Date("2027-12-01T00:00:00Z");
  const base = { play_account_ref: "r", trial_started: "2027-11-01T00:00:00Z", trial_until: "2027-11-08T00:00:00Z" };
  const trial = buildAcekorClaims({
    accountId: "33333333-3333-3333-3333-333333333333",
    installId: "install-acekor-0000-0001",
    state: {
      ...base,
      trial_started: "2027-11-28T00:00:00Z",
      trial_until: "2027-12-05T00:00:00Z",
      paid_tier: null,
      paid_until: null,
      auto_renew: null,
    },
    now,
    jti: "jti-trial",
  });
  const max = buildAcekorClaims({
    accountId: "33333333-3333-3333-3333-333333333333",
    installId: "install-acekor-0000-0001",
    state: { ...base, paid_tier: "max", paid_until: "2027-12-31T12:00:00Z", auto_renew: false },
    now,
    jti: "jti-max",
  });
  const acekanner = await signerFromSeed(TEST_SEED, "test", TOKEN_TYPE);
  return {
    note: "Generated by supabase/tests/deno/acekor_vectors_test.ts with ACEK_WRITE_VECTORS=1. Test keys only.",
    keyId: "test",
    publicKey: s.publicKey,
    trial: { token: await s.sign({ ...trial }), claims: trial },
    max: { token: await s.sign({ ...max }), claims: max },
    acekannerTyped: await acekanner.sign({ ...max }),
  };
}

Deno.test("ACEKOR app test vectors are up to date", async () => {
  const v = JSON.stringify(await vectors(), null, 2) + "\n";
  let write = false;
  try {
    write = Deno.env.get("ACEK_WRITE_VECTORS") === "1";
  } catch {
    // No env permission: compare only.
  }
  if (write) await Deno.writeTextFile(path, v);
  assertEquals(await Deno.readTextFile(path), v);
});
