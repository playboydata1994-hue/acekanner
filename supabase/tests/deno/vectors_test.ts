// Test vectors shared with the app (app/test/fixtures/entitlement_vectors.json):
// the Dart verifier must accept exactly what this server signs.
import { assertEquals } from "jsr:@std/assert@1.0.13";
import { buildClaims } from "../../functions/_shared/entitlement.ts";
import { signerFromSeed } from "../../functions/_shared/jws.ts";
import { TEST_SEED } from "./helpers.ts";

const path = new URL("../../../app/test/fixtures/entitlement_vectors.json", import.meta.url);

async function vectors() {
  const s = await signerFromSeed(TEST_SEED, "test");
  const now = new Date("2026-11-17T00:00:00Z");
  const base = { free_limit: 100, lease_holder: true, play_account_ref: "r" };
  const free = buildClaims({
    accountId: "11111111-1111-1111-1111-111111111111",
    installId: "install-phone-aaaa-0001",
    state: { ...base, free_used: 37, lease: 63, premium_until: null },
    now,
    jti: "jti-free",
  });
  const premium = buildClaims({
    accountId: "11111111-1111-1111-1111-111111111111",
    installId: "install-phone-aaaa-0001",
    state: { ...base, free_used: 37, lease: 63, premium_until: "2027-11-17T00:00:00Z" },
    now,
    jti: "jti-premium",
  });
  const other = await signerFromSeed(btoa(String.fromCharCode(...new Uint8Array(32).fill(7))), "test");
  return {
    note: "Generated by supabase/tests/deno/vectors_test.ts with ACEK_WRITE_VECTORS=1. Test keys only.",
    keyId: "test",
    publicKey: s.publicKey,
    free: { token: await s.sign({ ...free }), claims: free },
    premium: { token: await s.sign({ ...premium }), claims: premium },
    otherKey: await other.sign({ ...premium }),
  };
}

Deno.test("app test vectors are up to date", async () => {
  const v = JSON.stringify(await vectors(), null, 2) + "\n";
  let write = false;
  try {
    write = Deno.env.get("ACEK_WRITE_VECTORS") === "1";
  } catch {
    // No env permission: compare only.
  }
  if (write) {
    await Deno.writeTextFile(path, v);
  }
  assertEquals(await Deno.readTextFile(path), v);
});
